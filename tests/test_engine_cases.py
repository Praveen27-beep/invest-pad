"""The ten hand-computed cases from fixtures/engine_cases.json.

THESE ARE THE SPECIFICATION. Every number in that file was derived by hand from
docs/ENGINE_SPEC.md, not generated by code. If an implementation disagrees with one of
them, the implementation is wrong.

Cases are implemented across Sessions 2-5 and each must fail individually and BY NAME
until then -- a collection error that reports nothing is the one outcome this harness
exists to prevent.
"""

from __future__ import annotations

from decimal import Decimal
from typing import Any

import pytest

from engine.errors import MissingPriceError
from engine.holdings import compute_holdings
from engine.lots import compute_lots
from engine.realised import compute_realised
from engine.reconcile import reconcile
from engine.xirr import compute_period_xirr, compute_xirr
from tests.conftest import FIXTURES, dec, load_json, to_date, to_transaction

CASES: list[dict[str, Any]] = load_json(FIXTURES / "engine_cases.json")["cases"]
CASE_IDS: list[str] = [c["name"] for c in CASES]


def only_holding(transactions: list[Any]) -> Any:
    """Single-ISIN cases: assert exactly one open position and return it."""
    holdings = compute_holdings(transactions)
    assert len(holdings) == 1, f"expected one open position, got {len(holdings)}"
    return holdings[0]


def check_holdings(case: dict[str, Any]) -> None:
    """Cases 1-3: weighted-average cost, proportional cost removal, bonus dilution."""
    expected = case["expected"]
    holding = only_holding([to_transaction(r) for r in case["transactions"]])

    assert holding.quantity == dec(expected["quantity"])
    # The load-bearing assertion. A disposal removes cost PROPORTIONALLY and free
    # shares leave the pool alone, so `invested` is what catches a wrong cost-pool rule.
    assert holding.invested == dec(expected["invested"])
    assert holding.avg_cost == dec(expected["avg_cost"])


def check_xirr(case: dict[str, Any]) -> None:
    """Case 4: a rate that is exactly solvable by hand."""
    expected = case["expected"]
    transactions = [to_transaction(r) for r in case["transactions"]]
    prices = {k: dec(v) for k, v in case.get("prices", {}).items()}

    result = compute_xirr(transactions, prices, to_date(case["as_of"]))

    assert result is not None, "solver returned None for a well-formed series"
    tolerance = dec(expected.get("tolerance", "0.0005"))
    assert abs(Decimal(str(result)) - dec(expected["xirr_all"])) <= tolerance


def check_raises(case: dict[str, Any]) -> None:
    """Case 5: a missing price must RAISE, never resolve to a number.

    Silently valuing an unpriced holding at zero understates XIRR catastrophically.
    This case exists to make that failure mode impossible to ship.
    """
    transactions = [to_transaction(r) for r in case["transactions"]]
    prices = {k: dec(v) for k, v in case.get("prices", {}).items()}

    with pytest.raises(MissingPriceError):
        compute_xirr(transactions, prices, to_date(case["as_of"]))


def check_period_xirr(case: dict[str, Any]) -> None:
    """Case 10: mid-period cash flows must not be folded into the endpoints.

    A period XIRR built from only the opening and terminal values would report ~2.05
    here instead of ~0.05, because the money the client ADDED mid-period gets counted as
    growth. Forty times apart, so the coarse tolerance still catches it.
    """
    expected = case["expected"]
    transactions = [to_transaction(r) for r in case["transactions"]]
    prices = {k: dec(v) for k, v in case.get("prices", {}).items()}

    result = compute_period_xirr(
        transactions,
        prices,
        to_date(case["period_start"]),
        dec(case["opening_value"]),
        to_date(case["as_of"]),
    )

    assert result is not None, "solver returned None for a well-formed series"
    tolerance = dec(expected["tolerance"])
    assert abs(Decimal(str(result)) - dec(expected["xirr_period"])) <= tolerance


def check_realised(case: dict[str, Any]) -> None:
    """Case 6: one disposal splitting across two FIFO lots, each classified."""
    expected = case["expected"]
    transactions = [to_transaction(r) for r in case["transactions"]]

    realised = compute_realised(transactions)
    assert len(realised) == len(expected["realised"])

    for actual, want in zip(realised, expected["realised"], strict=True):
        assert actual.quantity == dec(want["quantity"])
        assert actual.cost == dec(want["cost"])
        assert actual.proceeds == dec(want["proceeds"])
        assert actual.gain == dec(want["gain"])
        assert actual.term.value == want["term"]

    # What remains open after FIFO consumption -- read from the LOTS, not from
    # compute_holdings. ENGINE_SPEC:110 says "remaining open: 50 @ 300", which is the
    # surviving lot's cost. The weighted average here is 250, because a disposal removes
    # cost proportionally and never moves the average. Both numbers are right for their
    # own method; this case asserts the FIFO one.
    lots = compute_lots(transactions)
    open_quantity = sum((lot.quantity_open for lot in lots), Decimal("0"))
    open_cost = sum((lot.quantity_open * lot.cost_per_unit for lot in lots), Decimal("0"))
    assert open_quantity == dec(expected["open_quantity"])
    assert open_cost / open_quantity == dec(expected["open_avg_cost"])


def check_reconcile(case: dict[str, Any]) -> None:
    """Cases 7-8: the corporate-action detector, firing and staying quiet."""
    expected = case["expected"]
    transactions = [to_transaction(r) for r in case["transactions"]]
    declared = {k: dec(v) for k, v in case["declared_holdings"].items()}

    discrepancies = reconcile(transactions, declared)
    assert len(discrepancies) == expected["discrepancy_count"]

    if expected["discrepancy_count"] == 0:
        return

    found = discrepancies[0]
    assert Decimal(str(found.ratio)) == dec(expected["ratio"])
    assert expected["likely_cause_contains"].lower() in (found.likely_cause or "").lower()


def check_dedupe(case: dict[str, Any]) -> None:
    """Case 9: importing the same rows twice inserts nothing the second time.

    Enforced for real by a UNIQUE INDEX in Session 5. Here it checks the pure key
    derivation that index depends on.
    """
    from engine.dedupe import dedupe, make_dedupe_key

    expected = case["expected"]
    transactions = [to_transaction(r) for r in case["transactions"]]

    first, skipped_first = dedupe(transactions, set())
    assert len(first) == expected["inserted_first"]
    assert skipped_first == 0

    stored = {make_dedupe_key(t) for t in first}
    second, skipped_second = dedupe(transactions, stored)
    assert len(second) == expected["inserted_second"]
    assert skipped_second == len(transactions)

    holding = only_holding(first)
    assert holding.quantity == dec(expected["final_quantity"])


def dispatch(case: dict[str, Any]) -> None:
    """Route a case to its checker by the shape of what it asserts."""
    expected = case["expected"]

    if case.get("import_twice"):
        return check_dedupe(case)
    if "raises" in expected:
        return check_raises(case)
    if "xirr_period" in expected:
        return check_period_xirr(case)
    if "xirr_all" in expected:
        return check_xirr(case)
    if "realised" in expected:
        return check_realised(case)
    if "discrepancy_count" in expected:
        return check_reconcile(case)
    if "quantity" in expected:
        return check_holdings(case)

    pytest.fail(f"no checker matches case shape: {sorted(expected)}")


def test_all_cases_are_present() -> None:
    """Guard the harness itself: ten cases, ten distinct names."""
    assert len(CASES) == 10
    assert len(set(CASE_IDS)) == 10


@pytest.mark.parametrize("case", CASES, ids=CASE_IDS)
def test_engine_case(case: dict[str, Any]) -> None:
    dispatch(case)
